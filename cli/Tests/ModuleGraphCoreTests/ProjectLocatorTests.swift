import Foundation
import Testing
@testable import ModuleGraphCore

@Suite struct ProjectLocatorTests {
    @Test func findsPackagesAndProjectsAndSkipsIgnoredFolders() throws {
        let root = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: root) }
        for path in [
            "Packages/Core/Package.swift",
            "Packages/Core/.build/checkouts/Dep/Package.swift",
            "Vendor/Lib/Package.swift",
            "Generated/Package.swift",
            "App.xcodeproj/project.pbxproj",
            "App.xcodeproj/Nested/Package.swift",
            ".gitignore",
        ] {
            let url = root.appendingPathComponent(path)
            try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
            try Data().write(to: url)
        }
        try "# comment\n/Generated/\nVendor/Lib\n*.log\n".write(to: root.appendingPathComponent(".gitignore"), atomically: true, encoding: .utf8)

        let location = ProjectLocator.locate(root: root)
        // .build is always skipped, Generated by the .gitignore; a path with a slash isn't understood, so Vendor/Lib is kept.
        #expect(location.packageDirectories.map(\.lastPathComponent) == ["Core", "Lib"])
        #expect(location.xcodeProjects.map(\.lastPathComponent) == ["App.xcodeproj"])
    }
}
